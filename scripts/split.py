#!/usr/bin/env python3
"""The library split (batch 204, commission section 1).

Reads the `import` lines of the files under `HPC/`, computes the import closure of
`HPC.BJ59.BJ59E` (the build of the library `HPC`), and writes the root file `HPCExtra.lean`:
one `import` line, in `LC_ALL=C` sorted order, for every module under `HPC/` that is outside that
closure and outside `HPC/Archive` and `HPC/Census`.

Check 1: every module under `HPC/` is in exactly one of: the closure of `HPC.lean`, the imports of
`HPCExtra.lean`, `HPC/Archive`, `HPC/Census`.

Check 2 (with `--env FILE`): the closure equals, as a set, the `HPC.*` modules (without the root
module `HPC`) listed in FILE, one per line, as written by
  lake env lean scripts/HPCModules.lean > /tmp/hpc-env-modules.txt

Run from the repository root:
  python3 scripts/split.py [--env /tmp/hpc-env-modules.txt] [--no-write]
"""
import os
import re
import sys

TARGET = "HPC.BJ59.BJ59E"
IMPORT_RE = re.compile(r"^import\s+([A-Za-z0-9_.']+)\s*(--.*)?$")

HEADER = """/-!
# Extra: modules outside the classification's import closure

Every module under `HPC/` that the library `HPC` (the import closure of `HPC.BJ59.BJ59E`) does not
build, other than those of `HPC/Archive` and `HPC/Census`: working files of the Theorem 3 and 4
campaign (`HPC/Fold`), the non-vacuity and certificate files of batches 196 to 202, the band and
cube models of `HPC/Plane`, `HPC.Plane.Theorem6Direct`, and counterexamples cited by the ledgers.
No theorem of the classification depends on them. Generated by `scripts/split.py`; build with
`lake build HPCExtra`.
-/
"""


def module_of(path):
    return path[:-len(".lean")].replace(os.sep, ".")


def imports_of(path):
    """The imports in the header of a Lean file (before its first command)."""
    out = []
    in_block = 0
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            s = line.strip()
            if in_block:
                in_block += s.count("/-") - s.count("-/")
                continue
            if not s or s.startswith("--"):
                continue
            if s.startswith("/-"):
                in_block = s.count("/-") - s.count("-/")
                continue
            m = IMPORT_RE.match(s)
            if m:
                out.append(m.group(1))
                continue
            break
    return out


def main():
    args = sys.argv[1:]
    env_file = None
    if "--env" in args:
        env_file = args[args.index("--env") + 1]
    write = "--no-write" not in args

    files = []
    for root, _dirs, names in os.walk("HPC"):
        for n in names:
            if n.endswith(".lean"):
                files.append(os.path.join(root, n))
    modules = {module_of(f): f for f in files}
    graph = {m: imports_of(f) for m, f in modules.items()}

    closure = set()
    stack = [TARGET]
    while stack:
        m = stack.pop()
        if m in closure:
            continue
        if m not in modules:
            continue  # Mathlib or other external modules
        closure.add(m)
        stack.extend(graph[m])

    archive = {m for m in modules if m.startswith("HPC.Archive.")}
    census = {m for m in modules if m.startswith("HPC.Census.")}
    extra = sorted((set(modules) - closure - archive - census),
                   key=lambda s: s.encode("utf-8"))

    if write:
        with open("HPCExtra.lean", "w", encoding="utf-8") as fh:
            for m in extra:
                fh.write(f"import {m}\n")
            fh.write("\n")
            fh.write(HEADER)

    # Check 1: the partition.
    extra_read = set(imports_of("HPCExtra.lean"))
    hpc_root = imports_of("HPC.lean")
    root_closure = set()
    stack = list(hpc_root)
    while stack:
        m = stack.pop()
        if m in root_closure or m not in modules:
            continue
        root_closure.add(m)
        stack.extend(graph[m])
    parts = [("HPC", root_closure), ("HPCExtra", extra_read),
             ("HPC/Archive", archive), ("HPC/Census", census)]
    bad = []
    for m in sorted(modules):
        k = sum(1 for _n, s in parts if m in s)
        if k != 1:
            bad.append((m, [n for n, s in parts if m in s]))
    print(f"modules under HPC/: {len(modules)}")
    for n, s in parts:
        print(f"  {n}: {len(s)}")
    print(f"  root file HPC.lean imports: {', '.join(hpc_root)}")
    if bad:
        print(f"check 1 FAILED: {len(bad)} modules not in exactly one part")
        for m, ps in bad:
            print(f"    {m}: {ps}")
    else:
        print("check 1 passed: every module under HPC/ is in exactly one part")

    # Check 2: against the environment's module list.
    if env_file:
        with open(env_file, encoding="utf-8") as fh:
            env = {l.strip() for l in fh if l.strip().startswith("HPC.")}
        env.discard("HPC")
        if env == root_closure:
            print(f"check 2 passed: closure ({len(root_closure)}) equals the environment's "
                  f"HPC.* modules ({len(env)})")
        else:
            print(f"check 2 FAILED: only in closure {sorted(root_closure - env)}; "
                  f"only in environment {sorted(env - root_closure)}")
    else:
        print("check 2 not run (no --env file)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
