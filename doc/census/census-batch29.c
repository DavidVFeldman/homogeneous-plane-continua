/* Census for batch 29 -- `S3ZigFree`, and the reconciliation of COMMISSION.md sec.0.
 *
 * Three regimes of itinerary are censused, all with the same counting
 * convention: an itinerary is a base centre ts[0] followed by k turning
 * targets ts[1..k], all in [L+1, H-1], directions alternating, one level per
 * step; `k` is the number of turning targets, so the list `ts` has k+1
 * entries.  This is batch 26's convention and batch 28's `wturns = |ts| - 1`.
 *
 *   regime 0 -- free zigzags: alternating directions and nothing else.
 *               This is the quantity batch 26 tabulated (`S3`).
 *   regime 1 -- `IsZig`: k >= 2, amplitudes |t_{j+1} - t_j| strictly
 *               increasing from the first, last two entries (L+1, H-1) or
 *               (H-1, L+1).
 *   regime 2 -- `IsZigFree`: the same with the first amplitude exempt, i.e.
 *               |t2 - t1| < |t3 - t2| < ... only.
 *
 * `FoldsOnto f len c` -- a 1-Lipschitz time assignment beta with beta 0 = 0,
 * beta j < len and |f j - c (beta j)| <= 1 -- is decided exactly by
 * reachability, the set of admissible times being a bitmask over walk times.
 * One O(n) sweep per walk resolves every basepoint of the chain at once:
 *
 *   G i = { u : rho[i], rho[i+1], ..., rho[n-1] folds starting at time u }
 *   T i = { u : rho[i], rho[i-1], ..., rho[0]   folds starting at time u }
 *
 * and basepoint i is served iff 0 is in G i and in T i.  Note that bit 0 of
 * the mask at rho[i] already forces |rho i - ts[0]| <= 1, so the base-centre
 * clause is part of the fold and not an extra restriction.
 *
 * Walks are generated by iterative deepening on k, so the first walk that
 * serves a basepoint has the least k.  Sweeping stops as soon as every
 * basepoint of the chain is served.
 *
 * Sections:
 *   1. the turn-count table, in all three regimes, spans 4..12  (sec.0)
 *   2. the ladder check: is every basepoint within two of an extreme served
 *      by [L+1, H-1, L+1] resp. [H-1, L+1, H-1]?  (the batch-29 theorem)
 *   3. `S3ZigFree` at every basepoint of bing 0 4 .. bing 0 12
 *   4. `S3ZigFree` on random and grid subchains of bing 0 12 of span >= 9
 *
 * Usage: census-batch29 [seed]
 */

#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef unsigned __int128 u128;

/* ------------------------------------------------------------ bing chains */

typedef struct { int *v; int n; } Path;

static Path bpath(int a, int b) {
  Path p;
  int d = a < b ? b - a : a - b;
  if (d <= 2) {
    p.n = d + 1;
    p.v = (int *)malloc(sizeof(int) * p.n);
    int s = (a <= b) ? 1 : -1;
    for (int u = 0; u < p.n; u++) p.v[u] = a + s * u;
    return p;
  }
  int mid = (a < b) ? b - 1 : b + 1;
  int c = (a < b) ? a + 1 : a - 1;
  Path p1 = bpath(a, mid), p2 = bpath(mid, c), p3 = bpath(c, b);
  p.n = p1.n + p2.n - 1 + p3.n - 1;
  p.v = (int *)malloc(sizeof(int) * p.n);
  memcpy(p.v, p1.v, sizeof(int) * p1.n);
  memcpy(p.v + p1.n, p2.v + 1, sizeof(int) * (p2.n - 1));
  memcpy(p.v + p1.n + p2.n - 1, p3.v + 1, sizeof(int) * (p3.n - 1));
  free(p1.v); free(p2.v); free(p3.v);
  return p;
}

/* -------------------------------------------------------------- the sweep */

#define MAXN 20000
#define MAXW 128

static u128 Gm[MAXN], Tm[MAXN];
static int minturns[MAXN];
static int chainN;
static const int *chainV;
static int chainL, chainH;
static int remaining;
static int curk;                 /* turn count of the walk being swept */

static inline u128 nbr(u128 m, u128 full) { return (m | (m << 1) | (m >> 1)) & full; }

/* Sweep one walk over the whole chain, marking the basepoints it serves. */
static void sweep(const signed char *w, int len) {
  u128 one = (u128)1;
  u128 full = (len >= 128) ? ~(u128)0 : ((one << len) - 1);
  u128 allow[64];
  for (int v = chainL; v <= chainH; v++) {
    u128 m = 0;
    for (int u = 0; u < len; u++) {
      int d = v - w[u];
      if (d <= 1 && d >= -1) m |= one << u;
    }
    allow[v - chainL] = m;
  }
  int n = chainN;
  Gm[n - 1] = allow[chainV[n - 1] - chainL];
  for (int i = n - 2; i >= 0; i--) Gm[i] = allow[chainV[i] - chainL] & nbr(Gm[i + 1], full);
  Tm[0] = allow[chainV[0] - chainL];
  for (int i = 1; i < n; i++) Tm[i] = allow[chainV[i] - chainL] & nbr(Tm[i - 1], full);
  for (int i = 0; i < n; i++) {
    if (minturns[i] >= 0) continue;
    if ((Gm[i] & Tm[i] & one) != 0) { minturns[i] = curk; remaining--; }
  }
}

/* Does the single walk `w` serve basepoint `i`? */
static int walk_serves(const signed char *w, int len, int i) {
  u128 one = (u128)1;
  u128 full = (len >= 128) ? ~(u128)0 : ((one << len) - 1);
  u128 allow[64];
  for (int v = chainL; v <= chainH; v++) {
    u128 m = 0;
    for (int u = 0; u < len; u++) {
      int d = v - w[u];
      if (d <= 1 && d >= -1) m |= one << u;
    }
    allow[v - chainL] = m;
  }
  int n = chainN;
  u128 g = allow[chainV[n - 1] - chainL];
  for (int t = n - 2; t >= i; t--) g = allow[chainV[t] - chainL] & nbr(g, full);
  u128 h = allow[chainV[0] - chainL];
  for (int t = 1; t <= i; t++) h = allow[chainV[t] - chainL] & nbr(h, full);
  return (g & h & one) != 0;
}

/* -------------------------------------------------- itinerary enumeration */

#define MAXTS 16

static int ts[MAXTS];
static int gRegime, gTargetK, gSweeping;
static long gWalks;

static void walk_of(int k, signed char *w, int *lenout) {
  int len = 0;
  w[len++] = (signed char)ts[0];
  for (int j = 1; j <= k; j++) {
    int d = ts[j] > ts[j - 1] ? 1 : -1;
    for (int x = ts[j - 1] + d;; x += d) {
      assert(len < MAXW);
      w[len++] = (signed char)x;
      if (x == ts[j]) break;
    }
  }
  *lenout = len;
}

/* j targets already placed (ts[0..j]); lastamp/lastdir describe the step into ts[j]. */
static void dfs(int j, int lastamp, int lastdir, void (*visit)(int)) {
  if (gSweeping && remaining <= 0) return;
  if (j == gTargetK) {
    if (gRegime != 0) {
      /* the last two entries must be the two extreme bands, in either order */
      int a = ts[j - 1], b = ts[j];
      if (!((a == chainL + 1 && b == chainH - 1) || (a == chainH - 1 && b == chainL + 1)))
        return;
    }
    visit(j);
    return;
  }
  int cur = ts[j];
  int minamp = 1;
  if (gRegime == 1) minamp = lastamp + 1;
  if (gRegime == 2) minamp = (j == 1) ? 1 : lastamp + 1;
  for (int dir = -1; dir <= 1; dir += 2) {
    if (lastdir != 0 && dir == lastdir) continue;
    for (int amp = minamp;; amp++) {
      int nxt = cur + dir * amp;
      if (nxt < chainL + 1 || nxt > chainH - 1) break;
      ts[j + 1] = nxt;
      dfs(j + 1, amp, dir, visit);
    }
  }
}

static void visit_sweep(int k) {
  signed char w[MAXW];
  int len;
  walk_of(k, w, &len);
  gWalks++;
  sweep(w, len);
  /* stop early: caller checks `remaining` */
}

/* Enumerate all itineraries with exactly `k` turning targets and sweep each. */
static void sweep_all_with_k(int k) {
  gTargetK = k;
  gSweeping = 1;
  if (gRegime != 0 && k < 2) return;
  for (int c = chainL + 1; c <= chainH - 1 && remaining > 0; c++) {
    ts[0] = c;
    dfs(0, 0, 0, visit_sweep);
    if (remaining <= 0) return;
  }
}

/* Score every basepoint of the chain: minturns[i] = least turn count, or -1. */
static void census_chain(const int *rho, int n, int regime, int kmax) {
  chainV = rho; chainN = n; gRegime = regime;
  chainL = chainH = rho[0];
  for (int i = 1; i < n; i++) { if (rho[i] < chainL) chainL = rho[i]; if (rho[i] > chainH) chainH = rho[i]; }
  for (int i = 0; i < n; i++) minturns[i] = -1;
  remaining = n;
  gWalks = 0;
  if (chainH - chainL < 3) return;
  for (int k = 1; k <= kmax && remaining > 0; k++) { curk = k; sweep_all_with_k(k); }
}

/* Report every minimal itinerary at basepoint i (up to 16 of them). */
static int repI, repBest, repCnt;
static void visit_report(int k) {
  signed char w[MAXW];
  int len;
  walk_of(k, w, &len);
  if (!walk_serves(w, len, repI)) return;
  if (repBest < 0) repBest = k;
  if (k == repBest) {
    if (repCnt < 16) {
      printf("      [");
      for (int j = 0; j <= k; j++) printf("%s%d", j ? ", " : "", ts[j]);
      printf("]\n");
    }
    repCnt++;
  }
}

static void report_basepoint(const int *rho, int n, int i, int regime, int kmax) {
  chainV = rho; chainN = n; gRegime = regime;
  chainL = chainH = rho[0];
  for (int t = 1; t < n; t++) { if (rho[t] < chainL) chainL = rho[t]; if (rho[t] > chainH) chainH = rho[t]; }
  repI = i; repBest = -1; repCnt = 0; gSweeping = 0;
  for (int k = 1; k <= kmax && repBest < 0; k++) {
    gTargetK = k;
    if (regime != 0 && k < 2) continue;
    for (int c = chainL + 1; c <= chainH - 1; c++) { ts[0] = c; dfs(0, 0, 0, visit_report); }
  }
  printf("    basepoint %d (level %d): %d minimal itineraries with %d turning targets\n",
         i, rho[i], repCnt, repBest);
}

/* ------------------------------------------------------------- the ladders */

/* Is every basepoint within two of an extreme served by the corresponding
   ladder -- [L+1, H-1, L+1] below, [H-1, L+1, H-1] above? */
static void ladder_check(const int *rho, int n, int *tested, int *failed) {
  chainV = rho; chainN = n;
  chainL = chainH = rho[0];
  for (int i = 1; i < n; i++) { if (rho[i] < chainL) chainL = rho[i]; if (rho[i] > chainH) chainH = rho[i]; }
  *tested = 0; *failed = 0;
  if (chainH - chainL < 3) return;
  signed char up[MAXW], dn[MAXW];
  int lup, ldn;
  ts[0] = chainL + 1; ts[1] = chainH - 1; ts[2] = chainL + 1; walk_of(2, up, &lup);
  ts[0] = chainH - 1; ts[1] = chainL + 1; ts[2] = chainH - 1; walk_of(2, dn, &ldn);
  for (int i = 0; i < n; i++) {
    if (rho[i] <= chainL + 2) {
      (*tested)++;
      if (!walk_serves(up, lup, i)) { (*failed)++;
        printf("    LADDER FAILURE (up) at basepoint %d, level %d\n", i, rho[i]); }
    } else if (rho[i] >= chainH - 2) {
      (*tested)++;
      if (!walk_serves(dn, ldn, i)) { (*failed)++;
        printf("    LADDER FAILURE (down) at basepoint %d, level %d\n", i, rho[i]); }
    }
  }
}

/* ------------------------------------------------- faithfulness (for a hit) */

static int faithful(const int *rho, int n) {
  for (int t = 0; t + 1 < n; t++) {
    int d = rho[t + 1] - rho[t];
    if (d > 1 || d < -1) return 0;
  }
  for (int s = 0; s < n; s++)
    for (int t = s + 1; t < n; t++)
      for (int hs = -1; hs <= 1; hs++) {
        if (s + hs < 0 || s + hs >= n) continue;
        int h = rho[s + hs];
        for (int ks = -1; ks <= 1; ks++) {
          if (t + ks < 0 || t + ks >= n) continue;
          int k = rho[t + ks];
          int ad = h - k; if (ad < 0) ad = -ad;
          if (ad < 3) continue;
          int w1 = (h < k) ? k - 1 : k + 1;
          int w2 = (h < k) ? h + 1 : h - 1;
          int ok = 0;
          for (int r = s + 1; r < t && !ok; r++)
            if (rho[r] == w1)
              for (int r2 = r + 1; r2 < t; r2++)
                if (rho[r2] == w2) { ok = 1; break; }
          if (!ok) return 0;
        }
      }
  return 1;
}

/* ------------------------------------------------------------------ main  */

static unsigned long long rstate;
static unsigned long long rnd(void) {
  rstate ^= rstate << 13; rstate ^= rstate >> 7; rstate ^= rstate << 17;
  return rstate;
}

static int subbuf[MAXN];
static const char *regname[3] = { "free zigzags", "IsZig", "IsZigFree" };

int main(int argc, char **argv) {
  rstate = (argc > 1) ? (unsigned long long)atoll(argv[1]) : 29ULL;

  /* ---------------- 1. the turn-count table, all three regimes ----------- */
  printf("=== 1. maximum over basepoints of the least number of turning targets ===\n");
  printf("    (counting convention: an itinerary is ts[0] plus k turning targets;\n");
  printf("     the number reported is max over basepoints of the least such k)\n");
  for (int regime = 0; regime <= 2; regime++) {
    printf("\n  regime %d (%s):\n", regime, regname[regime]);
    for (int N = 4; N <= 12; N++) {
      Path p = bpath(0, N);
      census_chain(p.v, p.n, regime, 8);
      int mx = -1, unserved = 0, unserved_extreme = 0;
      long hist[16]; memset(hist, 0, sizeof(hist));
      for (int i = 0; i < p.n; i++) {
        if (minturns[i] < 0) { unserved++; if (p.v[i] == 0 || p.v[i] == N) unserved_extreme++; }
        else { if (minturns[i] > mx) mx = minturns[i]; if (minturns[i] < 16) hist[minturns[i]]++; }
      }
      printf("    span %2d (%5d links): max least k = %d ; unserved %d (of them at an extreme "
             "level %d) ; distribution", N, p.n, mx, unserved, unserved_extreme);
      for (int k = 0; k < 16; k++) if (hist[k]) printf(" %d:%ld", k, hist[k]);
      printf(" ; walks swept %ld\n", gWalks);
      fflush(stdout);
      free(p.v);
    }
  }

  /* ---------------- 2. the ladder check ---------------------------------- */
  printf("\n=== 2. ladder check: every basepoint within two of an extreme ===\n");
  for (int N = 4; N <= 12; N++) {
    Path p = bpath(0, N);
    int tested, failed;
    ladder_check(p.v, p.n, &tested, &failed);
    printf("  bing 0 %2d: %d basepoints within two of an extreme, %d not served by the ladder\n",
           N, tested, failed);
    fflush(stdout);
    free(p.v);
  }

  /* ---------------- 3. S3ZigFree on whole chains ------------------------- */
  printf("\n=== 3. S3ZigFree at every basepoint of bing 0 N ===\n");
  for (int N = 4; N <= 12; N++) {
    Path p = bpath(0, N);
    census_chain(p.v, p.n, 2, 8);
    int mx = -1, unserved = 0;
    for (int i = 0; i < p.n; i++) {
      if (minturns[i] < 0) unserved++;
      else if (minturns[i] > mx) mx = minturns[i];
    }
    printf("  bing 0 %2d: %5d links, span %2d ... unserved basepoints: %d ; "
           "max least turning targets: %d\n", N, p.n, N, unserved, mx);
    if (unserved > 0) {
      printf("    FAILURE at basepoints:");
      int shown = 0;
      for (int i = 0; i < p.n && shown < 20; i++)
        if (minturns[i] < 0) { printf(" %d(level %d)", i, p.v[i]); shown++; }
      printf("\n");
    }
    fflush(stdout);
    free(p.v);
  }

  /* the hardest basepoints of spans 11 and 12, in the free family */
  for (int N = 11; N <= 12; N++) {
    Path p = bpath(0, N);
    census_chain(p.v, p.n, 2, 8);
    int mx = -1;
    for (int i = 0; i < p.n; i++) if (minturns[i] > mx) mx = minturns[i];
    int cnt = 0;
    for (int i = 0; i < p.n; i++) if (minturns[i] == mx) cnt++;
    printf("\n  span %d: %d basepoints attain the maximum %d; the first, with all its minimal "
           "itineraries:\n", N, cnt, mx);
    for (int i = 0, shown = 0; i < p.n && shown < 1; i++)
      if (minturns[i] == mx) { report_basepoint(p.v, p.n, i, 2, 8); shown++; }
    fflush(stdout);
    free(p.v);
  }

  /* ---------------- 4. subchains of bing 0 12 ---------------------------- */
  printf("\n=== 4. S3ZigFree on subchains of bing 0 12 of span >= 9 ===\n");
  {
    Path p = bpath(0, 12);
    int n = p.n;
    long tested = 0, badsub = 0, badpts = 0;
    long hist[16]; memset(hist, 0, sizeof(hist));
    int nsub = 4000;
    for (int it = 0; it < nsub; it++) {
      int a, b, L, H, tries = 0;
      do {
        a = (int)(rnd() % (unsigned)(n - 1));
        int rem = n - a, lenmax = rem < 4000 ? rem : 4000;
        b = a + 1 + (int)(rnd() % (unsigned)lenmax);
        if (b >= n) b = n - 1;
        L = H = p.v[a];
        for (int t = a; t <= b; t++) { if (p.v[t] < L) L = p.v[t]; if (p.v[t] > H) H = p.v[t]; }
        tries++;
      } while (H - L < 9 && tries < 200);
      if (H - L < 9) continue;
      int m = b - a + 1;
      memcpy(subbuf, p.v + a, sizeof(int) * m);
      census_chain(subbuf, m, 2, 8);
      tested++;
      int mx = -1, unserved = 0;
      for (int i = 0; i < m; i++) {
        if (minturns[i] < 0) unserved++; else if (minturns[i] > mx) mx = minturns[i];
      }
      if (mx >= 0 && mx < 16) hist[mx]++;
      if (unserved > 0) {
        badsub++; badpts += unserved;
        printf("  SUBCHAIN FAILURE [%d, %d] span %d: %d basepoints; faithful=%d\n",
               a, b, H - L, unserved, m <= 600 ? faithful(subbuf, m) : -1);
        for (int i = 0, s = 0; i < m && s < 6; i++)
          if (minturns[i] < 0) { printf("    basepoint %d (level %d)\n", i, subbuf[i]); s++; }
        fflush(stdout);
      }
    }
    printf("  random subchains: tested %ld, with a failure %ld (%ld basepoints)\n",
           tested, badsub, badpts);
    printf("  max least turning targets, distribution:");
    for (int k = 0; k < 16; k++) if (hist[k]) printf(" %d:%ld", k, hist[k]);
    printf("\n");
    fflush(stdout);
    free(p.v);
  }
  {
    Path p = bpath(0, 12);
    int n = p.n;
    long tested = 0, badsub = 0, badpts = 0;
    int stride = 97;
    for (int a = 0; a < n; a += stride)
      for (int b = a + 1; b < n; b += stride) {
        int L = p.v[a], H = p.v[a];
        for (int t = a; t <= b; t++) { if (p.v[t] < L) L = p.v[t]; if (p.v[t] > H) H = p.v[t]; }
        if (H - L < 9) continue;
        int m = b - a + 1;
        memcpy(subbuf, p.v + a, sizeof(int) * m);
        census_chain(subbuf, m, 2, 8);
        tested++;
        int unserved = 0;
        for (int i = 0; i < m; i++) if (minturns[i] < 0) unserved++;
        if (unserved > 0) {
          badsub++; badpts += unserved;
          printf("  GRID SUBCHAIN FAILURE [%d, %d] span %d: %d basepoints\n", a, b, H - L, unserved);
          fflush(stdout);
        }
      }
    printf("  grid subchains (stride %d): tested %ld, with a failure %ld (%ld basepoints)\n",
           stride, tested, badsub, badpts);
    free(p.v);
  }
  return 0;
}
