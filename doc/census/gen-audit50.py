#!/usr/bin/env python3
"""Generate HPC/Fold/Audit50.lean from census-batch50-audit.txt.

The census of batch 50 writes a sample of the arms it meets, each with the
verdict its own program gives on every predicate it evaluates.  This script
turns that sample into a Lean file in which the *definitions* of those
predicates are decided by the kernel on the same objects, so that a disagreement
between the census and the development would be a build failure.  The commission
of batch 50 asks for exactly this audit.

Usage: python3 gen-audit50.py > HPC/Fold/Audit50.lean
"""

import re
import sys

PREDS = [
    ("highAt", "HighAt {a} (0 + 1) (0 + 8)", "highAt"),
    ("leg3Valley", "Leg3Valley {a} 0", "leg3Valley"),
    ("leg3Ceil", "Leg3Ceil {a} 0", "leg3Ceil"),
    ("valley4", "Valley4 {a} 0", "valley4"),
    ("valley5", "Valley5 {a} 0", "valley5"),
    ("ceilW4", "CeilW4 {a} 0", "ceilW4"),
    ("bottomW4", "BottomW4 {a} 0", "bottomW4"),
    ("topW5", "TopW5 {a} 0", "topW5"),
    ("foldsLam",
     "FoldsOnto {a} (lamLen (0 + 3) (0 + 9) 0)\n      (lamCenter (0 + 3) (0 + 9) 0)", "foldsLam"),
    ("foldsVee",
     "FoldsOnto {a} (veeLen (0 + 5) (0 + 9) 0)\n      (veeCenter (0 + 5) (0 + 9) 0)", "foldsVee"),
    ("foldsW3",
     "FoldsOnto {a} (leg3Len 0 (0 + 9) (0 + 6) (0 + 4))\n      (leg3Walk 0 (0 + 9) (0 + 6) (0 + 4))",
     "foldsW3"),
    ("foldsW4",
     "FoldsOnto {a} (leg3Len 0 (0 + 9) (0 + 7) (0 + 7))\n      (leg3Walk' 0 (0 + 9) (0 + 7) (0 + 2))",
     "foldsW4"),
    ("foldsW5",
     "FoldsOnto {a} (leg3Len 0 (0 + 9) (0 + 7) (0 + 4))\n      (leg3Walk 0 (0 + 9) (0 + 7) (0 + 4))",
     "foldsW5"),
]


def parse(path):
    arms = []
    cur = None
    for line in open(path):
        m = re.match(r"arm (\S+) gen=(-?\d+) basepoint=(\d+) (\S+) len=(\d+)", line)
        if m:
            cur = {"tag": m.group(1), "gen": int(m.group(2)), "bp": int(m.group(3)),
                   "which": m.group(4), "len": int(m.group(5)), "verdict": {}}
            arms.append(cur)
            continue
        if cur is None:
            continue
        m = re.match(r"\s+nat16: 0x([0-9A-F]+)", line)
        if m:
            cur["nat"] = int(m.group(1), 16)
            continue
        m = re.match(r"\s+levels:(.*)", line)
        if m:
            cur["levels"] = [int(x) for x in m.group(1).split()]
            continue
        for k, v in re.findall(r"(\w+)=(\d)", line):
            cur["verdict"][k] = int(v)
    return arms


def main():
    arms = parse("census-batch50-audit.txt")
    out = sys.stdout
    out.write("""import HPC.Fold.Decide
import HPC.Fold.LandmarkW

/-!
# The definition audit of batch 50

The commission of batch 50 asks that every predicate a census evaluates and the development also
defines be checked against the definition, by kernel evaluation in Lean, on a sample of the
census's own objects — and that the report say which predicates were audited and on how many
objects. This file is that check, and it is generated by `gen-audit50.py` from the sample
`census-batch50-audit.txt` that `census-batch50.c` writes as it runs.

Each arm below is one the census met, read off a base-sixteen numeral, and each theorem states the
verdict the census recorded for it. The predicates audited are

* `HighAt` — the branch hypothesis, whose misreading cost the censuses of batches 46 to 48 a
  refutation they could not see;
* `Leg3Valley`, `Leg3Ceil` — the profile clauses of batch 48;
* `Valley4`, `Valley5`, `CeilW4`, `BottomW4`, `TopW5` — the landmark clauses of the three walks
  (`HPC/Fold/LandmarkW.lean`);
* `FoldsOnto`, for each of the five walks the census decides: the two canonical walks and `w₃`,
  `w₄`, `w₅`.

The fold verdicts are the census's own dynamic program, and they are auditable at all only because
of `HPC/Fold/Decide.lean`: `foldsB_iff` proves that program equivalent to the definition of
`FoldsOnto`, and the instance it carries is what `decide` uses below. Before that file a census
verdict of *no fold* could not be checked in Lean against anything.

A disagreement between the census and the definitions would be a build failure here.
-/

set_option maxRecDepth 40000000

namespace HPC.Fold

namespace Audit50

/-! ## Reading an arm off a numeral -/

/-- The arm whose level at the step `i` is the `i`-th base-sixteen digit of `n`. -/
def armOf (n : ℕ) (m : ℕ) : Fin m → ℤ := fun i => (((n >>> (4 * i.val)) &&& 15 : ℕ) : ℤ)

/-! ## The predicates, made decidable

Each is a bounded quantifier over the steps of the arm, so each is decidable; the instances only
have to unfold the definition. -/

instance (m : ℕ) (f : Fin m → ℤ) (tl th : ℤ) : Decidable (HighAt f tl th) := by
  unfold HighAt; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (Leg3Valley f L) := by
  unfold Leg3Valley; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (Leg3Ceil f L) := by
  unfold Leg3Ceil; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (Valley4 f L) := by
  unfold Valley4; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (Valley5 f L) := by
  unfold Valley5; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (CeilW4 f L) := by
  unfold CeilW4; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (BottomW4 f L) := by
  unfold BottomW4; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (TopW5 f L) := by
  unfold TopW5; infer_instance

""")
    for idx, arm in enumerate(arms, 1):
        name = "a%d" % idx
        out.write("/-! ## Arm %d — %s, generator %d, basepoint %d, %s arm, %d steps -/\n\n"
                  % (idx, arm["tag"], arm["gen"], arm["bp"], arm["which"], arm["len"]))
        lv = " ".join(str(x) for x in arm["levels"])
        lines, cur_line = [], "Levels: `"
        for tok in lv.split():
            if len(cur_line) + len(tok) + 1 > 96:
                lines.append(cur_line)
                cur_line = tok
            else:
                cur_line = cur_line + (" " if cur_line and not cur_line.endswith("`") else "") + tok
        lines.append(cur_line + "`.")
        out.write("/-- " + "\n".join(lines) + " -/\n")
        out.write("def %s : Fin %d → ℤ :=\n  armOf 0x%X %d\n\n" % (name, arm["len"], arm["nat"], arm["len"]))
        for key, stmt, _ in PREDS:
            v = arm["verdict"].get(key)
            if v is None:
                continue
            claim = stmt.format(a=name)
            if v:
                out.write("theorem %s_%s :\n    %s := by\n  decide +kernel\n" % (name, key, claim))
            else:
                out.write("theorem %s_not_%s :\n    ¬ (%s) := by\n  decide +kernel\n"
                          % (name, key, claim))
        out.write("\n")

    out.write("""/-! ## What was audited

%d arms of the census, of %d to %d steps, and on each of them the %d predicates above: %d kernel
checks in all, every one agreeing with the census. -/

end Audit50

end HPC.Fold
""" % (len(arms), min(a["len"] for a in arms), max(a["len"] for a in arms), len(PREDS),
       sum(len([1 for k, _, _ in PREDS if k in a["verdict"]]) for a in arms)))


if __name__ == "__main__":
    main()
