#!/usr/bin/env python3
"""Generate HPC/Fold/Audit52.lean from census-batch52-audit.txt.

The census of batch 52 writes a sample of the arms it meets, each with the
verdict its own program gives on every predicate it evaluates.  This script
turns that sample into a Lean file in which the *definitions* of those
predicates are decided by the kernel on the same objects, so that a disagreement
between the census and the development would be a build failure.  The commission
of batch 52 asks for exactly this audit.

Usage: python3 gen-audit52.py > HPC/Fold/Audit52.lean
"""

import re
import sys

PREDS = [
    ("lowAt", "LowAt {a} (0 + 1) (0 + 8)", "lowAt"),
    ("Ceil4R", "Ceil4R {a} 0", "Ceil4R"),
    ("Floor3R", "Floor3R {a} 0", "Floor3R"),
    ("MidW4R", "MidW4R {a} 0", "MidW4R"),
    ("FloorW4R", "FloorW4R {a} 0", "FloorW4R"),
    ("TopW4R", "TopW4R {a} 0", "TopW4R"),
    ("Ceil5R", "Ceil5R {a} 0", "Ceil5R"),
    ("BottomW5R", "BottomW5R {a} 0", "BottomW5R"),
    ("foldsVeeL6",
     "FoldsOnto {a} (veeLen (0 + 6) (0 + 9) 0)\n      (veeCenter (0 + 6) (0 + 9) 0)", "foldsVeeL6"),
    ("foldsLamL4",
     "FoldsOnto {a} (lamLen (0 + 4) (0 + 9) 0)\n      (lamCenter (0 + 4) (0 + 9) 0)", "foldsLamL4"),
    ("foldsW3R",
     "FoldsOnto {a} (leg3Len 0 (0 + 9) (0 + 6) (0 + 4))\n      (leg3Walk' 0 (0 + 9) (0 + 6) (0 + 5))",
     "foldsW3R"),
    ("foldsW4R",
     "FoldsOnto {a} (leg3Len 0 (0 + 9) (0 + 7) (0 + 7))\n      (leg3Walk 0 (0 + 9) (0 + 7) (0 + 7))",
     "foldsW4R"),
    ("foldsW5R",
     "FoldsOnto {a} (leg3Len 0 (0 + 9) (0 + 7) (0 + 4))\n      (leg3Walk' 0 (0 + 9) (0 + 7) (0 + 5))",
     "foldsW5R"),
]


def parse(path):
    arms = []
    cur = None
    for line in open(path):
        m = re.match(r"arm (\S+) gen=(-?\d+) basepoint=(\d+) (\S+) len=(\d+)", line)
        if m:
            cur = {"tag": m.group(1), "gen": int(m.group(2)), "bp": int(m.group(3)),
                   "which": m.group(4), "len": int(m.group(5)), "verdict": {}}
            arms.append(cur)
            continue
        if cur is None:
            continue
        m = re.match(r"\s+nat16: 0x([0-9A-F]+)", line)
        if m:
            cur["nat"] = int(m.group(1), 16)
            continue
        m = re.match(r"\s+levels:(.*)", line)
        if m:
            cur["levels"] = [int(x) for x in m.group(1).split()]
            continue
        for k, v in re.findall(r"(\w+)=(\d)", line):
            cur["verdict"][k] = int(v)
    return arms


def main():
    arms = parse("census-batch52-audit.txt")
    out = sys.stdout
    out.write("""import HPC.Fold.Decide
import HPC.Fold.ArmReflect

/-!
# The definition audit of batch 52

The commission asks that every predicate a census evaluates and the development also defines be
checked against the definition, by kernel evaluation in Lean, on a sample of the census's own
objects. This file is that check for the predicates of the branch `L + 5`, and it is generated by
`gen-audit52.py` from the sample `census-batch52-audit.txt` that `census-batch52.c` writes as it
runs.

Each arm below is one the census met at a basepoint of the branch `L + 5`, read off a base-sixteen
numeral, and each theorem states the verdict the census recorded for it. The predicates audited are

* `LowAt` — the branch hypothesis at `L + 5`;
* `Ceil4R`, `Floor3R`, `MidW4R`, `FloorW4R`, `TopW4R`, `Ceil5R`, `BottomW5R` — the reflected
  landmark clauses of `HPC/Fold/ArmReflect.lean`, each read on the arm itself;
* `FoldsOnto`, for each of the five reflected walks the census decides: the V-walk based at `L + 6`
  and the Λ-walk based at `L + 4` — the reflections of the two canonical walks of the branch
  `L + 4` — and the reflections of `w₃`, `w₄`, `w₅`.

The fold verdicts are the census's own dynamic program, auditable because `foldsB_iff`
(`HPC/Fold/Decide.lean`) proves that program equivalent to the definition of `FoldsOnto`.

A disagreement between the census and the definitions would be a build failure here.
-/

set_option maxRecDepth 40000000

namespace HPC.Fold

namespace Audit52

/-! ## Reading an arm off a numeral -/

/-- The arm whose level at the step `i` is the `i`-th base-sixteen digit of `n`. -/
def armOf (n : ℕ) (m : ℕ) : Fin m → ℤ := fun i => (((n >>> (4 * i.val)) &&& 15 : ℕ) : ℤ)

/-! ## The predicates, made decidable

Each is a bounded quantifier over the steps of the arm, so each is decidable; the instances only
have to unfold the definition. -/

instance (m : ℕ) (f : Fin m → ℤ) (tl th : ℤ) : Decidable (LowAt f tl th) := by
  unfold LowAt; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (Ceil4R f L) := by
  unfold Ceil4R; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (Floor3R f L) := by
  unfold Floor3R; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (MidW4R f L) := by
  unfold MidW4R; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (FloorW4R f L) := by
  unfold FloorW4R; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (TopW4R f L) := by
  unfold TopW4R; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (Ceil5R f L) := by
  unfold Ceil5R; infer_instance

instance (m : ℕ) (f : Fin m → ℤ) (L : ℤ) : Decidable (BottomW5R f L) := by
  unfold BottomW5R; infer_instance


""")
    for idx, arm in enumerate(arms, 1):
        name = "a%d" % idx
        out.write("/-! ## Arm %d — %s, generator %d, basepoint %d, %s arm, %d steps -/\n\n"
                  % (idx, arm["tag"], arm["gen"], arm["bp"], arm["which"], arm["len"]))
        lv = " ".join(str(x) for x in arm["levels"])
        lines, cur_line = [], "Levels: `"
        for tok in lv.split():
            if len(cur_line) + len(tok) + 1 > 96:
                lines.append(cur_line)
                cur_line = tok
            else:
                cur_line = cur_line + (" " if cur_line and not cur_line.endswith("`") else "") + tok
        lines.append(cur_line + "`.")
        out.write("/-- " + "\n".join(lines) + " -/\n")
        out.write("def %s : Fin %d → ℤ :=\n  armOf 0x%X %d\n\n" % (name, arm["len"], arm["nat"], arm["len"]))
        for key, stmt, _ in PREDS:
            v = arm["verdict"].get(key)
            if v is None:
                continue
            claim = stmt.format(a=name)
            if v:
                out.write("theorem %s_%s :\n    %s := by\n  decide +kernel\n" % (name, key, claim))
            else:
                out.write("theorem %s_not_%s :\n    ¬ (%s) := by\n  decide +kernel\n"
                          % (name, key, claim))
        out.write("\n")

    out.write("""/-! ## What was audited

%d arms of the census, of %d to %d steps, and on each of them the %d predicates above: %d kernel
checks in all, every one agreeing with the census. -/

end Audit52

end HPC.Fold
""" % (len(arms), min(a["len"] for a in arms), max(a["len"] for a in arms), len(PREDS),
       sum(len([1 for k, _, _ in PREDS if k in a["verdict"]]) for a in arms)))


if __name__ == "__main__":
    main()
